<#
.SYNOPSIS
  Writes the OAuth client ids of a release build into a generated source file, from the environment, without echoing them.
.DESCRIPTION
  Reads GOOGLE_OAUTH_CLIENT_ID, GOOGLE_OAUTH_CLIENT_SECRET and MICROSOFT_OAUTH_CLIENT_ID from the environment (the `release` GitHub
  environment's secrets; the Mac release uses the same names) and writes src/TimeTug.Presentation/Startup/ReleaseOAuthIds.g.cs, which is
  git-ignored. Google needs its id and its secret together (a Google desktop client has a secret that is not confidential for an installed
  app), Microsoft only its id; a family with nothing set stays unconfigured and the app then says "isn't set up in this build".
  The values are never printed: the output names the families written and nothing else. Each value must be a plain token (letters, digits and
  . _ ~ : / + = @ -) so that it cannot break out of the C# string it is written into.
  build-release-msix.ps1 calls this before the build and -Remove after it, so the ids do not stay on disk.
.PARAMETER OutputPath
  Default: src/TimeTug.Presentation/Startup/ReleaseOAuthIds.g.cs under the repository.
.PARAMETER Require
  Fail unless both families are complete. A real release passes this; the pull-request dry run supplies fake values.
.PARAMETER Remove
  Delete the generated file and do nothing else.
#>
[CmdletBinding()]
param(
    [string]$OutputPath,
    [switch]$Require,
    [switch]$Remove
)

$ErrorActionPreference = 'Stop'
$script:Repo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
if (-not $OutputPath) { $OutputPath = Join-Path $script:Repo 'src/TimeTug.Presentation/Startup/ReleaseOAuthIds.g.cs' }

function Test-OAuthValue([string]$Value) {
    return $Value -match '^[A-Za-z0-9._~:/+=@-]{1,512}$'
}

# The C# for the generated half of ReleaseOAuthIds; null for a family that is not set. Throws (without the value) for one that is not a plain token.
function New-OAuthIdsSource([string]$GoogleId, [string]$GoogleSecret, [string]$MicrosoftId) {
    foreach ($pair in @(@('GOOGLE_OAUTH_CLIENT_ID', $GoogleId), @('GOOGLE_OAUTH_CLIENT_SECRET', $GoogleSecret), @('MICROSOFT_OAUTH_CLIENT_ID', $MicrosoftId))) {
        if ($pair[1] -and -not (Test-OAuthValue $pair[1])) { throw "$($pair[0]) has characters that are not allowed in an OAuth client value (it is not printed here)" }
    }
    if ([bool]$GoogleId -ne [bool]$GoogleSecret) { throw 'set both GOOGLE_OAUTH_CLIENT_ID and GOOGLE_OAUTH_CLIENT_SECRET, or neither' }
    $lines = @()
    if ($GoogleId) {
        $lines += "        googleClientId = `"$GoogleId`";"
        $lines += "        googleClientSecret = `"$GoogleSecret`";"
    }
    if ($MicrosoftId) { $lines += "        microsoftClientId = `"$MicrosoftId`";" }
    if ($lines.Count -eq 0) { return $null }
    $body = $lines -join "`n"
    return @"
// <auto-generated>
// Written by scripts/release/write-oauth-ids.ps1 from the release environment just before a release build. Never committed.
// </auto-generated>
#nullable enable
namespace TimeTug.Presentation.Startup;

public static partial class ReleaseOAuthIds
{
    static partial void Provide(ref string? googleClientId, ref string? googleClientSecret, ref string? microsoftClientId)
    {
$body
    }
}

"@
}

function Get-OAuthFamilies([string]$GoogleId, [string]$MicrosoftId) {
    $names = @()
    if ($GoogleId) { $names += 'google' }
    if ($MicrosoftId) { $names += 'microsoft' }
    return $names
}

if ($MyInvocation.InvocationName -ne '.') {
    if ($Remove) {
        if (Test-Path -LiteralPath $OutputPath) { Remove-Item -LiteralPath $OutputPath -Force }
        Write-Host 'Removed the generated OAuth ids file (if there was one)'
        return
    }

    $googleId = $env:GOOGLE_OAUTH_CLIENT_ID
    $googleSecret = $env:GOOGLE_OAUTH_CLIENT_SECRET
    $microsoftId = $env:MICROSOFT_OAUTH_CLIENT_ID
    if ($Require) {
        if (-not $googleId -or -not $googleSecret) { throw 'GOOGLE_OAUTH_CLIENT_ID and GOOGLE_OAUTH_CLIENT_SECRET must both be set in the release environment' }
        if (-not $microsoftId) { throw 'MICROSOFT_OAUTH_CLIENT_ID must be set in the release environment' }
    }

    $source = New-OAuthIdsSource $googleId $googleSecret $microsoftId
    if ($null -eq $source) {
        if (Test-Path -LiteralPath $OutputPath) { Remove-Item -LiteralPath $OutputPath -Force }
        Write-Host 'No OAuth ids in the environment: this build embeds none (Google and Microsoft sign-in will say they are not set up)'
        return
    }

    [System.IO.File]::WriteAllText($OutputPath, $source, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host ('OAuth ids written for: ' + ((Get-OAuthFamilies $googleId $microsoftId) -join ', '))
}
